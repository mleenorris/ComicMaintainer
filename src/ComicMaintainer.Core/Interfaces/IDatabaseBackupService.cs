namespace ComicMaintainer.Core.Interfaces;

/// <summary>A database backup file on disk.</summary>
public sealed record DatabaseBackupInfo(string Name, long SizeBytes, DateTime CreatedUtc);

/// <summary>Outcome of staging a restore.</summary>
/// <param name="Source">The backup name (or <c>upload</c>) that was staged.</param>
/// <param name="SafetyBackup">Backup of the live database taken before staging.</param>
/// <param name="RestartRequired">Always true: the swap happens on the next startup.</param>
public sealed record DatabaseRestoreResult(string Source, DatabaseBackupInfo SafetyBackup, bool RestartRequired = true);

/// <summary>
/// Creates, lists, prunes and restores consistent online backups of the
/// application's SQLite database.
/// </summary>
/// <remarks>
/// Backup names are generated by the service (<c>comicmaintainer-yyyyMMdd-HHmmss[-suffix].db</c>)
/// and every method that accepts a name rejects anything that does not match
/// that pattern or does not resolve inside <see cref="BackupDirectory"/>
/// with <see cref="ArgumentException"/>.
/// </remarks>
public interface IDatabaseBackupService
{
    /// <summary>Absolute path of the directory backups are written to.</summary>
    string BackupDirectory { get; }

    /// <summary>True when a restore has been staged and will be applied on the next start.</summary>
    bool IsRestorePending { get; }

    /// <summary>Takes a consistent copy of the live database.</summary>
    Task<DatabaseBackupInfo> CreateBackupAsync(CancellationToken cancellationToken = default);

    /// <summary>Backups, newest first.</summary>
    IReadOnlyList<DatabaseBackupInfo> ListBackups();

    /// <summary>Returns false when the backup does not exist.</summary>
    bool DeleteBackup(string name);

    /// <summary>Opens a backup for reading, or returns null when it does not exist.</summary>
    Stream? OpenBackup(string name);

    /// <summary>Deletes all but the newest <c>DatabaseBackupRetention</c> backups. Returns the number deleted.</summary>
    int PruneBackups();

    /// <summary>
    /// Validates an existing backup, takes a safety backup of the live database and
    /// stages the selected backup to replace it on the next start.
    /// </summary>
    /// <exception cref="FileNotFoundException">The backup does not exist.</exception>
    /// <exception cref="InvalidDataException">The file is not a valid ComicMaintainer database.</exception>
    Task<DatabaseRestoreResult> StageRestoreAsync(string name, CancellationToken cancellationToken = default);

    /// <summary>As <see cref="StageRestoreAsync"/>, for an uploaded database file.</summary>
    /// <exception cref="InvalidDataException">The file is not a valid ComicMaintainer database.</exception>
    Task<DatabaseRestoreResult> StageRestoreFromStreamAsync(Stream content, CancellationToken cancellationToken = default);

    /// <summary>Discards a staged restore. Returns false when none was pending.</summary>
    bool CancelPendingRestore();
}

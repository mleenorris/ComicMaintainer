using System.Collections.Concurrent;
using System.Threading.Channels;
using ComicMaintainer.Core.Interfaces;
using ComicMaintainer.Core.Utilities;
using Microsoft.Extensions.Logging;

namespace ComicMaintainer.Core.Services;

/// <summary>
/// Default <see cref="IFileCoverWarmupQueue"/>: the files whose covers are wanted, generated one
/// at a time by <see cref="RunAsync"/> through <see cref="IFileCoverCacheService.WarmUpAsync"/>,
/// which skips covers already cached and gives way to covers someone is waiting for.
/// </summary>
/// <remarks>
/// Files are queued by the archive-metadata scan, for every file whose metadata it records (files
/// added by the file watcher or a library scan, and files changed outside the app), and by the
/// processor, for every file it rewrites or renames. At most <see cref="MaxPending"/> files wait;
/// a cover that does not get queued is generated by its first request, as without the queue.
/// </remarks>
public sealed class FileCoverWarmupQueue : IFileCoverWarmupQueue
{
    /// <summary>Most files waiting at once.</summary>
    internal const int MaxPending = 10_000;

    private readonly IFileCoverCacheService _covers;
    private readonly ILogger<FileCoverWarmupQueue> _logger;
    private readonly Channel<string> _channel = Channel.CreateUnbounded<string>(new UnboundedChannelOptions
    {
        SingleReader = true,
        SingleWriter = false,
    });

    private readonly ConcurrentDictionary<string, byte> _pending = new(StringComparer.Ordinal);
    private int _pendingCount;
    private int _warmedCount;

    public FileCoverWarmupQueue(IFileCoverCacheService covers, ILogger<FileCoverWarmupQueue> logger)
    {
        _covers = covers;
        _logger = logger;
    }

    /// <summary>Files waiting (for tests).</summary>
    internal int PendingCount => Volatile.Read(ref _pendingCount);

    /// <summary>Files taken off the queue and handed to the cover cache (for tests).</summary>
    internal int WarmedCount => Volatile.Read(ref _warmedCount);

    /// <inheritdoc />
    public void Enqueue(string filePath)
    {
        if (string.IsNullOrWhiteSpace(filePath))
        {
            return;
        }

        if (Interlocked.Increment(ref _pendingCount) > MaxPending || !_pending.TryAdd(filePath, 0))
        {
            Interlocked.Decrement(ref _pendingCount);
            return;
        }

        if (!_channel.Writer.TryWrite(filePath))
        {
            _pending.TryRemove(filePath, out _);
            Interlocked.Decrement(ref _pendingCount);
        }
    }

    /// <summary>
    /// Generates the queued covers one at a time until <paramref name="cancellationToken"/> is
    /// cancelled. A cover that fails is logged at Debug and left to its first request.
    /// </summary>
    public async Task RunAsync(CancellationToken cancellationToken)
    {
        try
        {
            await foreach (var filePath in _channel.Reader.ReadAllAsync(cancellationToken))
            {
                _pending.TryRemove(filePath, out _);
                Interlocked.Decrement(ref _pendingCount);
                try
                {
                    await _covers.WarmUpAsync(filePath, cancellationToken);
                }
                catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
                {
                    throw;
                }
                catch (Exception ex) when (ex is not OutOfMemoryException)
                {
                    _logger.LogDebug(ex, "Could not generate the cover of {FilePath} ahead of time; its first request will",
                        LoggingHelper.SanitizePathForLog(filePath));
                }
                finally
                {
                    Interlocked.Increment(ref _warmedCount);
                }
            }
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            // Shutting down; covers still queued are generated by their first request.
        }
    }
}
